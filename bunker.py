        so.ver += 1
        st.ver += 1
        self.know(o, t, key, st)
        self.know(t, o, key, so)
        for pl in self.players:                     # чужие знания устарели
            if pl.id in (o.id, t.id):
                continue
            pl.known.pop((o.id, key), None)
            pl.known.pop((t.id, key), None)
        self.log(f"🤝 «{o.name}» и «{t.name}» обменялись характеристикой "
                 f"«{CARD_TITLES[key]}» (тайно).", "act")
