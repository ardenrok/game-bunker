def apply_action(g, i, decision):
    """decision: ('pass',...) или ('play', aid, payload).
    Возвращает строку секрета (для intimate-панели) или None."""
    kind, aid, payload = decision
    p = g.get(i)
    if kind != "play" or not p.alive:
        return None
    slot = p.cards.get("action")
    if slot is None or slot.used or slot.empty:
        return None
    others = [q.id for q in g.alive() if q.id != i]
    if aid in ("peek_one", "peek_full", "steal_card", "force_open",
               "cure_other", "sabotage", "infect", "protect_other"):
        if isinstance(payload, tuple):
            payload = payload[0]
        if payload is None and others:
            payload = g.rnd.choice(others)
        if payload is None:
            return None
        payload = int(payload)
        if payload not in others:
            return None
    if aid == "peek_two":
        if not payload:
            pool = [x for x in others]
            if len(pool) < 2:
                return None
            payload = g.rnd.sample(pool, 2)
    if aid in ("swap_card", "give_card", "reroll_one"):
        if payload and payload[0] == "MARKET":
            strong = max((q for q in g.alive() if q.id != i),
                         key=lambda q: util_of(g, p, q), default=None)
            if not strong:
                return None
            hs_o = [k for k in g.hidden_keys(p) if k != "action"]
            hs_t = [k for k in g.hidden_keys(strong) if k != "action"]
            inter = [k for k in hs_o if k in hs_t]
            payload = (strong.id, g.rnd.choice(inter) if inter else None)
        if not payload or payload[1] is None:
            return None
        if aid == "reroll_one":
            payload = payload[1]
    if aid in ("cure_self", "protect_self", "protect_self_next", "double_vote",
               "reroll_all", "revive_shield", "peek_threat"):
        payload = None
    g.act_use(p)
    secret = None
    try:
        if aid == "peek_one":
            secret = g.act_peek(p, payload)
        elif aid == "peek_two":
            secret = g.act_peek_two(p, payload)
        elif aid == "peek_full":
            secret = g.act_peek_full(p, payload)
        elif aid == "peek_threat":
            secret = g.act_peek_threat(p)
        elif aid == "swap_card":
            secret = g.act_swap(p, payload[0], payload[1])
        elif aid == "give_card":
            secret = g.act_give(p, payload[0], payload[1])
        elif aid == "steal_card":
            secret = g.act_steal(p, payload)
        elif aid == "protect_self":
            secret = g.act_protect_self(p)
        elif aid == "protect_self_next":
            secret = g.act_protect_self_next(p)
        elif aid == "protect_other":
            secret = g.act_protect_other(p, payload)
        elif aid == "double_vote":
            secret = g.act_double(p)
        elif aid == "reroll_one":
            secret = g.act_reroll(p, payload)
        elif aid == "reroll_all":
            secret = g.act_reroll_all(p)
        elif aid == "force_open":
            secret = g.act_force_open(p, payload)
        elif aid == "cure_self":
            secret = g.act_cure(p, p.id)
        elif aid == "cure_other":
            secret = g.act_cure(p, payload)
        elif aid == "sabotage":
            secret = g.act_sabotage(p, payload)
        elif aid == "infect":
            secret = g.act_infect(p, payload)
        elif aid == "revive_shield":
            secret = g.act_revive(p)
    except Exception as e:
        g.log(f"⚠ сбой карты «{slot.name}»: {e}", "act")
        secret = None
    return secret


def run_round(g, verbose=False):
    """Самодостаточный прогон одного раунда (для selftest).
    Боты всё решают сами; людей в этом режиме нет."""
    g.new_round()
    g.log(f"── РАУНД {g.round_no}: живых {len(g.alive())}, мест {g.capacity} ──", "sys")
    # фаза действий
    for i in g.alive_ids():
        d = bot_action(g, i)
        apply_action(g, i, d)
    # фаза раскрытия
    for i in g.alive_ids():
        k = bot_reveal(g, i)
        if k:
            c = g.get(i).cards[k]
            c.revealed = True
            g.log(f"📢 «{g.get(i).name}» открыл: {c.public_line()} (сила {c.value})", "reveal")
        elif g.get(i).forced:
            hs = g.hidden_keys(g.get(i))
            if hs:
                k = "profession" if g.get(i).forced == "profession" and "profession" in hs else hs[0]
                c = g.get(i).cards[k]
                c.revealed = True
                g.log(f"📢 «{g.get(i).name}» по приговору открыл: {c.public_line()}", "reveal")
    votes = {}
    last = getattr(g, "last_votes", {})
    for pid in g.alive_ids():
        t = bot_vote(g, pid, last)
        if t is not None:
            votes[pid] = t
    g.last_votes = dict(votes)
    nulls = {}
    for pid in g.alive_ids():
        n = bot_nullify(g, pid)
        if n is not None:
            nulls[pid] = n
            g.act_use(g.get(pid))
            g.log(f"⭕ «{g.get(pid).name}» готовится обнулить чей-то голос.", "act")
    g.log("─" * 46, "sys")
    kind, elim, counts = g.recount(votes)
    g.show_counts = counts
    g.reveal_next_threat()
    if verbose:
        for tag, line in g.logbook[-14:]:
            print(f"[{tag}] {line}")
    return kind, elim

