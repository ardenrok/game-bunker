def run_selftest(n_bots=7, capacity=3, seed=None, quiet=True):
    g = Game(dict(names=[BOT_NAMES[i % len(BOT_NAMES)] for i in range(n_bots)],
                  humans=[False] * n_bots,
                  capacity=capacity, seed=seed, privacy=False))
    if not quiet:
        s = g.scen
        print(f"☢ {s.cat[0]} · опасность {s.cat[2]}/10 · дней {s.cat[3]}")
        print(f"🏠 {s.bunk[0]} — {s.bunk[1]}")
    guard = 0
    while len(g.alive()) > g.capacity and guard < 30:
        guard += 1
        kind, elim = run_round(g)
        if not quiet:
            print(f"раунд {g.round_no}: kind={kind} elim={elim.name if elim else None}")
    surv = g.alive()
    if not quiet:
        print("\n✔ В БУНКЕРЕ:")
        for p in surv:
            prof = p.cards.get("profession")
            hlt = p.cards.get("health")
            print(f"  {p.label()}: {prof.name if prof else '—'} · {hlt.name if hlt else '—'}")
    g.close_log()
    return g


def main():
    os.environ.setdefault("TK_SILENCE_DEPRECATION", "1")
    argv = sys.argv[1:]
    if argv and argv[0].startswith("--selftest"):
        ok = 0
        for seed, bots, cap in ((7, 7, 3), (12345, 6, 2), (99, 8, 4),
                                (20260101, 5, 2), (555, 9, 5)):
            try:
                run_selftest(n_bots=bots, capacity=cap, seed=seed, quiet=True)
                ok += 1
                print(f"  ✔ seed={seed} bots={bots} cap={cap}")
            except Exception:
                import traceback
                traceback.print_exc()
                print(f"  ✘ FAIL seed={seed} bots={bots} cap={cap}")
                sys.exit(1)
        print(f"✔ SELFTEST OK — {ok}/5 прогонов прошли чисто")
        return
    try:
        App(uitest=any(a.startswith("--uitest") for a in argv))
    except tk.TclError as e:
        print("Не удалось открыть окно tkinter:", e)
        print("Запустите графический режим на машине с рабочим столом,")
        print("или проверьте движок без окна: python3 bunker.py --selftest")


if __name__ == "__main__":
    main()
