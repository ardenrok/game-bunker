class Card:
    __slots__ = ("key", "name", "desc", "value", "tags", "revealed",
                 "ver", "aid", "used", "empty")

    def __init__(self, key, name, desc, value, tags=(), aid=None, empty=False):
        self.key = key
        self.name = name
        self.desc = desc
        self.value = value
        self.tags = tuple(tags)
        self.revealed = False      # открыта ли карта всем за столом
        self.ver = 0               # версия — растёт при изменении
        self.aid = aid             # id карты-действия (для key="action")
        self.used = False
        self.empty = empty

    def public_line(self):
        return f"{CARD_ICONS.get(self.key, '')} {CARD_TITLES.get(self.key, '')}: {self.name}"

    def secret_line(self):
        return f"{self.public_line()} — сила {self.value}"

    def __repr__(self):
        return f"<Card {self.key}:{self.name} v={self.value}{' R' if self.revealed else ''}>"


