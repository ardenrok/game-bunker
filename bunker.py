    def _do_human_action(self, p, state):
        g = self.g
        aid = state["aid"]
        needs = ACTIONS[aid][3]
        payload = None
        try:
            if aid == "peek_two":
                first = int(state["target"].get())
                others2 = [q.id for q in g.alive() if q.id != p.id and q.id != first]
                payload = [first, self.g.rnd.choice(others2)] if others2 else [first]
            elif needs in ("target", "target_key"):
                payload = int(state["target"].get())
                if needs == "target_key":
                    payload = (int(state["target"].get()), state["key"].get())
            elif needs == "self_key":
                payload = (p.id, state["selfkey"].get())
        except Exception:
            self.open_overlay("Не выбрано", "Выберите цель и карту.",
                              lambda pr: None, "ВЕРНУТЬСЯ →",
                              lambda: self._action_panel(p), big=False)
            return
        secret = apply_action(g, p.id, ("play", aid, payload))
        self.sync_log()
        self.render_players()
        act = p.cards.get("action")
        ok = (act.used if act else True)
        self.open_overlay("РЕЗУЛЬТАТ КАРТЫ",
                          secret or "Карта не применилась. Неудачный расклад.",
                          lambda pr: None, "Готово ▶",
                          lambda: self.on_action_done(p, secret), big=False)

    def on_action_done(self, p, secret):
        self.close_overlay()
        self.qstep += 1
        self.render_players()
        self.tick(200, self.next_action_step)

    def next_action_step(self):
        g = self.g
        if self.phase != "actions":
            return
        if self.qstep >= len(self.queue):
            self.run_reveals()
            return
        pid = self.queue[self.qstep]
        p = g.get(pid)
        if not p.alive:
            self.qstep += 1
            self.tick(50, self.next_action_step)
            return
        if p.is_bot:
            decision = bot_action(g, pid)
            apply_action(g, pid, decision)
            self.qstep += 1
            self.sync_log()
            self.render_players()
            self.tick(420, self.next_action_step)
        else:
            self.human_action_overlay(p)

