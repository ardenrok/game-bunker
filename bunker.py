    # ── ГОЛОСОВАНИЕ: сбор голосов, счёт, изгнание ──
    def cast_votes(self, votes, outcomes_hook=None):
        """votes: dict voter_id -> target_id (или None).
        nullify: player.nullify = id игрока, чей голос аннулирован."""
        counts = {}
        annulled = []
        for v in self.alive():
            tgt = votes.get(v.id)
            if tgt is None:
                continue
            if any(x.nullify == v.id for x in self.alive() if x.nullify is not None):
                annulled.append(v.name)
                continue
            w = 2 if v.double else 1
            counts[tgt] = counts.get(tgt, 0) + w
        for tgt in list(counts):
            t = self.get(tgt)
            if not t.alive:
                counts.pop(tgt)
        return counts, annulled

    def elect(self, counts):
        """Возвращает ( eliminated_player | None, kind ) где kind: 'ok','tie','all_protected'."""
        cand = []
        for tgt, cnt in counts.items():
            t = self.get(tgt)
            if t.alive and not t.protected:
                cand.append((tgt, cnt))
        if not cand:
            return None, "all_protected"
        mx = max(c for _, c in cand)
        lead = [tgt for tgt, c in cand if c == mx]
        if len(lead) > 1:
            self._last_tie = lead
            return None, "tie"
        elim = self.get(lead[0])
        if elim.shield:
            elim.shield = False
            self.log(f"🩸 «{elim.name}» активирует КРОВНЫЙ КОНТРАКТ и остаётся!", "act")
            return None, "shield"
        elim.alive = False
        return elim, "ok"

    def recount(self, votes):
        """Полный цикл: логи, счёт, изгнание. Возвращает (outcome_kind, elim, counts)."""
        counts, annulled = self.cast_votes(votes)
        for an in annulled:
            self.log(f"⚠ Голос «{an}» аннулирован («Ставка на ноль»).", "vote")
        lines = []
        for v in self.alive():
            st = v.double and " (x2)" or ""
            tgt = self.get(votes.get(v.id))
            if tgt:
                lines.append(f"{v.name} → {tgt.name}{st}")
        self.log("Голоса: " + "; ".join(lines), "vote")
        for tgt in list(counts):
            t = self.get(tgt)
            if t.protected:
                self.log(f"🛡 Голосы против «{t.name}» ({counts[tgt]}) утонули в броне.", "vote")
        elim, kind = self.elect(counts)
        if kind == "ok":
            self.log(f"💀 ИЗГНАН: «{elim.name}». Соседи нарекли его обузой.", "elim")
            self.log_character_full(elim, "исключён")   # вылетевший раскрывает всё
            self.rounds_no_elim = 0
        elif kind == "tie":
            self.rounds_no_elim += 1
            names = " / ".join(self.get(x).name for x in self._last_tie)
            self.log(f"⚖ НИЧЬЯ: {names} — голоса делит тьма. Никто не изгнан.", "vote")
        elif kind == "all_protected":
            self.log("🛡 КАЖДЫЙ — ОБОРОВАННЫЙ: все кандидаты под защитой.", "vote")
        elif kind == "shield":
            self.rounds_no_elim += 1
        # счётчик обид на голосовавших
        for v in self.alive():
            tgt = votes.get(v.id)
            if tgt is not None:
                target = self.get(tgt)
                if target.alive and target.is_bot and target.id != v.id:
                    target.ai["grudge"][v.id] = target.ai["grudge"].get(v.id, 0) + 1
                if v.is_bot and target.id != v.id:
                    v.ai["warm"][target.id] = v.ai["warm"].get(target.id, 0) - 1
        return kind, elim, counts


