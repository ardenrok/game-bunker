    def next_reveal_step(self):
        g = self.g
        if self.phase != "reveals":
            return
        if self.qstep >= len(self.queue):
            self.run_votes()
            return
        pid = self.queue[self.qstep]
        p = g.get(pid)
        if not p.alive:
            self.qstep += 1
            self.tick(50, self.next_reveal_step)
            return
        hs = g.hidden_keys(p)
        if not hs:
            g.log(f"„{p.name}“ скрывать больше нечего.", "reveal")
            self.qstep += 1
            self.tick(200, self.next_reveal_step)
            return
        if p.is_bot:
            k = bot_reveal(g, pid)
            if k is None and p.forced:
                k = "profession" if (p.forced == "profession" and "profession" in hs) else hs[0]
            if k:
                c = p.cards[k]
                c.revealed = True
                why = " (по приговору)" if p.forced else ""
                g.log(f"📢 «{p.name}» открывает: {c.public_line()} "
                      f"— сила {c.value}{why}", "reveal")
            else:
                g.log(f"🤐 «{p.name}» молчит и прячет всё.", "reveal")
            p.forced = None
            self.qstep += 1
            self.sync_log()
            self.render_players()
            self.tick(420, self.next_reveal_step)
        else:
            self.human_reveal_overlay(p)

