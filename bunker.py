def pers(p):
    return PERSONS.get(p.person, ("Бот", {}))[1] if p.is_bot else {}


def util_of(g, obs, tgt):
    """Итоговая полезность с точки зрения наблюдателя (включ. угрозы)."""
    if tgt.id == obs.id or not tgt.alive:
        return 0.0
    s = 0.0
    hidden = 0
    for k in CARD_KEYS:
        c = tgt.cards.get(k)
        if c is None or c.empty:
            continue
        if c.revealed:
            s += float(c.value) + g.threat_bonus(c)
            continue
        info = obs.known.get((tgt.id, k))
        if info and info[2] == c.ver:
            s += float(info[1])
        else:
            s += (-1.4 if k == "phobia" else 2.0 if k == "action" else 3.8)
            hidden += 1
    for c in obs.extra if obs.id == tgt.id else []:
        pass
    for c in tgt.extra:
        if any(info[0] == c.name for kk, info in obs.known.items()):
            s += float(info[1])
    hv = tgt.cards["health"]
    hv_known = hv.revealed or g.knows(obs, tgt, "health")
    hv_val = hv.value if hv_known else 4.0
    if hv_val <= 1.0:
        s -= 3.5
    return s


def bot_action(g, i):
    """Возвращает ('pass', None, None) или ('play', aid, payload)."""
    p = g.get(i)
    if not p.is_bot or not p.alive:
        return ("pass", None, None)
    c = p.cards.get("action")
    pp = pers(p)
    if c is None or c.used or c.empty:
        return ("pass", None, None)
    aid = c.aid
    others = [q for q in g.alive() if q.id != i]
    if not others:
        return ("pass", None, None)
    threat_in = p.votes_in >= 2 or p.protected is False and p.votes_in >= 1
    weak = [q for q in others if util_of(g, p, q) < 8.0]
    strong = max(others, key=lambda q: util_of(g, p, q))
    r = g.rnd

    # 1) защита себя, когда жгут
    if aid in ("protect_self", "protect_self_next") and p.votes_in >= 1:
        return ("play", aid, None)
    if aid == "protect_self_next" and cheap(pp) and r.random() < 0.25:
        return ("play", aid, None)
    # 2) лечение слабого или себя
    if aid == "cure_self" and int(p.cards["health"].value) <= 3:
        return ("play", aid, None)
    if aid == "cure_other" and weak and r.random() < pp.get("mercy", 0.3):
        return ("play", aid, g.rnd.choice(weak).id)
    # 3) информация — любители
    if aid in ("peek_one", "peek_two", "peek_full", "peek_threat"):
        prop = 0.9 if pp.get("anti_secret", 0) > 0.4 else 0.45
        if r.random() < prop:
            if aid == "peek_threat":
                return ("play", aid, None)
            if aid == "peek_two":
                pick = r.sample(others, min(2, len(others)))
                return ("play", aid, [q.id for q in pick])
            tgt = strong if r.random() < 0.6 else r.choice(others)
            return ("play", aid, tgt.id)
    # 4) обмен/дар/кража
    if aid == "swap_card":
        hs = g.hidden_keys(p)
        good = [k for k in hs if k in g.hidden_keys(strong) and k != "action"]
        if good and util_of(g, p, strong) > 30 and r.random() < 0.5:
            return ("play", aid, (strong.id, "MARKET"))
    if aid == "give_card" and weak and r.random() < pp.get("mercy", 0) * 0.6:
        hs_g = [k for k in g.hidden_keys(p) if k != "action"]
        if hs_g:
            return ("play", aid, (g.rnd.choice(weak).id, r.choice(hs_g)))
    if aid == "steal_card" and r.random() < 0.35 + pp.get("aggr", 0) * 0.3:
        lots = [q for q in others if g.hidden_keys(q)]
        if lots:
            return ("play", aid, (max(lots, key=lambda q: util_of(g, p, q)).id, None))
    # 5) вандализм/заражение — раздолье злых
    if aid == "sabotage" and r.random() < 0.3 + pp.get("aggr", 0) * 0.5:
        tgt = strong if r.random() < 0.7 else r.choice(others)
        if g.hidden_keys(tgt):
            return ("play", aid, tgt.id)
    if aid == "infect" and r.random() < 0.25 + pp.get("aggr", 0) * 0.5:
        return ("play", aid, (strong if r.random() < 0.6 else r.choice(others)).id)
    # 6) хеджирование
    if aid == "double_vote" and r.random() < 0.5:
        return ("play", aid, None)
    if aid == "revive_shield" and r.random() < 0.4:
        return ("play", aid, None)
    if g.heads_to_fill() <= 2 and aid == "reroll_all" and util_of(g, p, p) < 22 and r.random() < 0.5:
        return ("play", aid, None)
    if aid == "reroll_one" and r.random() < 0.4:
        hs = g.hidden_keys(p)
        if hs:
            return ("play", aid, (i, r.choice(hs)))
    if aid == "force_open" and r.random() < 0.3 + pp.get("anti_secret", 0) * 0.4:
        return ("play", aid, strong.id)
    return ("pass", None, None)


def cheap(pp):
    return not pp.get("aggr", 0) > 0.7

def bot_reveal(g, i):
    """Бот решает, какую карту открыть столу (или None — промолчать)."""
    p = g.get(i)
    if not p.is_bot or not p.alive:
        return None
    pp = pers(p)
    hs = g.hidden_keys(p)
    if not hs:
        return None
    if p.forced:
        if p.forced == "profession" and "profession" in hs:
            return "profession"
        return g.rnd.choice(hs)
    # если угрозы уже известны — транслировать «медицину», когда она есть
    some_threat_tags = [tag for th in g.scen.revealed for tag in th.wanted]
    if some_threat_tags:
        gold = [k for k in ("profession", "health") if k in hs
                and p.cards[k].value >= 6
                and (p.cards[k].tags and any(t in some_threat_tags for t in p.cards[k].tags))]
        if gold:
            return g.rnd.choice(gold)
    prof = "profession" if ("profession" in hs and p.cards["profession"].value >= 5) else None
    nice = sorted(hs, key=lambda k: -p.cards[k].value)
    if g.rnd.random() < 0.55:                 # обычно показывать что-то положительное
        if prof:
            return prof
        best = nice[0]
        if p.cards[best].value >= 4:
            return best
    if pp.get("anti_secret", 0) > 0.4 and len(hs) > 5:
        return None                            # проныры любят молчать
    if nice and p.cards[nice[0]].value <= -3:
        return nice[-1]                        # обязан показать что-то: пусть худшее
    if nice:
        return g.rnd.choice(nice[:3])
    return None


def bot_vote(g, i, last_votes=None):
    """Возвращает target_id голоса бота (не себя)."""
    p = g.get(i)
    pp = pers(p)
    others = [q for q in g.alive() if q.id != i]
    if not others:
        return None
    util = {q.id: util_of(g, p, q) for q in others}
    avg = sum(util.values()) / max(1, len(util))
    score = {}
    for q in others:
        sc = (avg - util[q.id]) * (1.0 + 0.6 * pp.get("util", 0.5))
        sc += pp.get("grudge", 0.3) * (p.ai["grudge"].get(q.id, 0) * 1.4)
        sc += pp.get("anti_strong", 0) * (util[q.id] - avg) * 0.5
        secret = sum(1 for k in CARD_KEYS
                     if not (q.cards[k].revealed or g.knows(p, q, k)) if q.cards[k] and not q.cards[k].empty)
        sc += pp.get("anti_secret", 0) * secret * 0.35
        if q.cards["health"].revealed and q.cards["health"].value <= 1:
            sc += 1.6                          # будьте проще: труп — тоже выбор
        if pp.get("mercy", 0) > 0.6 and util[q.id] == min(util.values()):
            sc -= 2.5                          # филантроп щадит слабого
        if q.protected:
            sc -= 5.0                          # не тратить голос в стену
        if last_votes:
            bandwagon = sum(1 for vv, tt in (last_votes or {}).items()
                            if tt == q.id and vv != i)
            sc += pp.get("conform", 0.2) * bandwagon * 1.1
        score[q.id] = sc + g.rnd.uniform(0, 0.8)
    if g.rnd.random() < pp.get("bluff", 0.1):
        return g.rnd.choice(others).id
    return max(score, key=lambda k: score[k])


def bot_nullify(g, i):
    p = g.get(i)
    c = p.cards.get("action")
    if not (c and not c.used and c.aid == "nullify_vote"):
        return None
    foe = max(p.ai["grudge"], key=p.ai["grudge"].get) if p.ai["grudge"] else None
    if foe is not None and g.get(foe) and g.get(foe).alive and g.rnd.random() < 0.7:
        return foe
    return None

