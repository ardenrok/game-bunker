    # ── БАЗОВАЯ ОЦЕНКА ПОЛЕЗНОСТИ (кто интересен бункеру) ──
    def card_est(self, obs, owner, key):
        """Оценка силы карты ключа с точки зрения наблюдателя."""
        c = owner.cards.get(key)
        if c is None or c.empty:
            return 0.0, False
        known = c.revealed or self.knows(obs, owner, key)
        if known:
            return float(c.value) + self.threat_bonus(c), True
        base = 3.8
        if key == "phobia":
            base = -1.4
        if key == "action":
            base = 2.0
        return base, False

    def utility(self, obs, tgt):
        s = 0.0
        for k in CARD_KEYS:
            v, known = self.card_est(obs, tgt, k)
            if not known:
                v -= 0.4                 # неизвестность слегка настораживает
            s += v
        # проигрываем катастрофе дополнительный вес здоровью
        hv, hk = self.card_est(obs, tgt, "health")
        if hv <= 1.0:
            s -= 3.5                      # умирающий тянет на дно
        return s

